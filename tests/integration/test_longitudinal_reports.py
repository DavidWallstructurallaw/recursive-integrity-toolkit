@pytest.mark.parametrize("source_count,target_count", [(102, 1), (204, 102)])
def test_mapping_and_each_collision_level_obey_detail_cap(tmp_path, source_count, target_count):
    case = _case("directed_many_to_one")
    states = {f"SOURCE_{index:03}": f"TARGET_{index % target_count:03}" for index in range(source_count)}
    case["records"] = [{"dataset_version": version, "record_id": f"record_{index:03}",
                        "topic": state, "content": "bounded mapping fixture"}
                       for version, values in (("v1", states), ("v2", sorted(set(states.values()))))
                       for index, state in enumerate(values)]
    case["provenance"] = [{"dataset_version": row["dataset_version"], "record_id": row["record_id"],
        "source_type": "synthetic", "provenance_confidence": "confirmed", "external_grounding": "no",
        "parent_ids": [], "transformation": "generate"} for row in case["records"]]
    case["expected_pairs"][0]["mapping"]["state_mapping"] = states
    report, _, _ = _report(case, tmp_path)
    payload = _checked(report)
    pair = payload["inputs"]["longitudinal"]["comparisons"][0]
    entries, collisions = pair["mapping"]["entries"], pair["mapping_collisions"]
