    assert collisions["returned_count"] == min(target_count, 100)
    for group in collisions["items"]:
        sources = group["source_states"]
        assert sources["total_count"] == source_count // target_count
        assert sources["returned_count"] == min(source_count // target_count, 100)
        assert sources["omitted_count"] == sources["total_count"] - sources["returned_count"]
    metrics = payload["derived_metrics"]["longitudinal"]["comparisons"][0]
    assert _value(metrics, "support_retention_ratio") == 1
    assert _value(metrics, "support_delta") == 0
    for mode in ("hash", "omit"):
        view = privacy_view(report, mode="redacted", record_id_mode=mode,
                            protection=IdentifierProtection(secret=SECRET))
        safe = _checked(view)
        assert "SOURCE_" not in render_json(view) and "TARGET_" not in render_markdown(view)
        protected = safe["inputs"]["longitudinal"]["comparisons"][0]["mapping"]["entries"]
        assert protected["total_count"] == source_count
