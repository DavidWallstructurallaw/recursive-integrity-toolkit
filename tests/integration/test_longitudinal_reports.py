def _run():
    nullable = ("started_at", "completed_at", "duration_seconds", "python_version",
                "platform", "command", "config_hash", "random_seed")
    return {"run_id": "longitudinal-integration", "toolkit_version": "0.1.0.dev4",
            "report_schema_version": "1.2", **dict.fromkeys(nullable),
            "strict_mode": False, "redacted_mode": False, "network_call_count": 0,
            "deterministic": True, "privacy_mode": "standard", "run_status": "complete",
            "null_reasons": {name: "not_recorded" for name in nullable}}


def _case(name="observed_three_version"):
    return deepcopy(next(case for case in CASES if case["case_id"] == name))


def _load(case, tmp_path):
    tmp_path.mkdir(parents=True, exist_ok=True)
    loaded = {row["dataset_version"] for row in case["records"]}
    primary = next(version for version in reversed(case["selected_versions"]) if version in loaded)
    sources = []
    for index, version in enumerate(sorted(loaded)):
        path = tmp_path / f"records_{index}.jsonl"
        path.write_text("".join(json.dumps(row) + "\n" for row in case["records"]
                                if row["dataset_version"] == version), encoding="utf-8")
        role = (FileRole.LINEAGE_CONTEXT if version in case["context_versions"] else
                FileRole.RECORDS_PRIMARY if version == primary else FileRole.RECORDS_COMPARE)
        sources.append(InputSource(role, path))
    path = tmp_path / "provenance.jsonl"
    path.write_text("".join(json.dumps(row) + "\n" for row in case["provenance"]), encoding="utf-8")
    sources.append(InputSource(FileRole.PROVENANCE_MANIFEST, path))
    if case["order_document"] is not None:
        path = tmp_path / "order.json"
        path.write_text(json.dumps(case["order_document"]), encoding="utf-8")
        sources.append(InputSource(FileRole.VERSION_ORDER, path))
    return validate_bundle(AuditBundle(tuple(sources)))


def _declarations(case):
    loaded = {row["dataset_version"] for row in case["records"]}
    return tuple(series.SnapshotDeclaration(version, RepresentationConfig(**{
        key: value for key, value in declaration.items() if key != "state_semantics"
    }), declaration["state_semantics"], empty_scope=version not in loaded)
        for version, declaration in case["representations"].items())


def _selection(case, bundle, baseline="first", mappings=None):
    declarations = _declarations(case)
    if mappings is None:
        mappings = ()
        if case["case_id"] == "directed_many_to_one":
            earlier, later = declarations
            def descriptor(declaration):
                return select_field_representation((), dataset_versions=(declaration.dataset_version,),
                    config=declaration.representation).descriptor
            declared = case["expected_pairs"][0]["mapping"]
            mapping = StateMappingDeclaration(declared["direction"], descriptor(earlier), descriptor(later),
                earlier.state_semantics, later.state_semantics, declared["state_mapping"])
            mappings = (series.LongitudinalMapping(earlier.dataset_version, later.dataset_version, mapping),)
    return series.select_longitudinal_versions(bundle, declarations=declarations,
                                               baseline=baseline, mappings=mappings)


def _report(case, tmp_path, *, tail=False, lineage=False, limits=None, baseline="first"):
    bundle = _load(case, tmp_path)
    selection = _selection(case, bundle, baseline)
    result = series.analyze_longitudinal(bundle, selection=selection, lineage=lineage,
        lineage_limits=limits, tail_options=TailSelectionOptions("singleton_count") if tail else None)
    return assemble_report(bundle, run=_run(), longitudinal=result), result, bundle


def _checked(report):
    payload = report.to_dict()
    Draft202012Validator(SCHEMA).validate(payload)
    validate_report(payload)
    assert tuple(payload) == SECTION_ORDER
    assert payload["run"]["report_schema_version"] == "1.2"
    assert payload["capabilities"] == payload["observability"]["capabilities"]
    assert "input_signature" not in json.dumps(payload)
    assert "selection_signature" not in json.dumps(payload)
    return payload


def _fraction(actual, expected):
    if expected is None:
        assert actual is None
    else:
        assert actual == pytest.approx(float(Fraction(expected)), rel=1e-12, abs=1e-12)


def _pair_rows(payload):
    inputs = payload["inputs"]["longitudinal"]
    snapshots = {row["snapshot_id"]: row["dataset_version"] for row in inputs["snapshots"]}
    rows = {row["comparison_id"]: row for row in payload["derived_metrics"]["longitudinal"]["comparisons"]}
    return {(snapshots[pair["earlier_snapshot_id"]], snapshots[pair["later_snapshot_id"]]):
            rows[pair["comparison_id"]] for pair in inputs["comparisons"]}


def _value(row, name):
    return row[name]["value"]


@pytest.mark.parametrize("name", [case["case_id"] for case in CASES
                                  if "expected_snapshots" in case and case["case_id"] != "missing_order"])
@pytest.mark.parametrize("tail", [False, True])
def test_public_distribution_fields_match_frozen_oracles(tmp_path, name, tail):
    case = _case(name)
    report, result, _ = _report(case, tmp_path, tail=tail)
    payload = _checked(report)
    inputs = payload["inputs"]["longitudinal"]
    assert [row["dataset_version"] for row in inputs["snapshots"]] == case["selected_versions"]
    assert [row["snapshot_id"] for row in inputs["snapshots"]] == [
        f"s{index:04}" for index in range(1, len(case["selected_versions"]) + 1)]
    assert inputs["comparison_count"] == len(result.comparisons)
    observed = payload["observed_facts"]["longitudinal"]["snapshots"]
    derived = payload["derived_metrics"]["longitudinal"]["snapshots"]
    for descriptor, facts, metrics in zip(inputs["snapshots"], observed, derived, strict=True):
        oracle = case["expected_snapshots"][descriptor["dataset_version"]]
        assert facts["snapshot_id"] == metrics["snapshot_id"] == descriptor["snapshot_id"]
        for name, expected in (("record_count", "record_count"),
                               ("representation_eligible_record_count", "eligible_count"),
                               ("representation_excluded_record_count", "excluded_count")):
            assert _value(facts, name) == oracle[expected]
        assert _value(metrics, "support_size") == oracle["support_size"]
        _fraction(_value(metrics, "gini_simpson_diversity"), oracle["diversity"])
        assert facts["record_count"]["evidence_class"] == "observed_fact"
        assert facts["record_count"]["scope_id"] == descriptor["population_scope_id"]
        assert metrics["support_size"]["scope_id"] == descriptor["representation_scope_id"]
    pairs = _pair_rows(payload)
    for oracle in case["expected_pairs"]:
        row = pairs[oracle["earlier"], oracle["later"]]
        if "expected_pair_error" in oracle:
            assert row["support_delta"]["status"] == "unavailable"
            assert _value(row, "support_delta") is None
            assert "R_LONGITUDINAL_PAIR_BLOCKED" in row["support_delta"]["reason_codes"]
            continue
        expected = oracle["distribution"]
        assert _value(row, "record_count_delta") == expected["record_count_delta"]
        assert _value(row, "support_delta") == expected["support_delta"]
        _fraction(_value(row, "gini_simpson_diversity_delta"), expected["diversity_delta"])
        for name, field in (("extinct_states", "missing_states"), ("added_states", "added_states"),
                            ("retained_states", "retained_states")):
            details = _value(row, name)
            assert (None if details is None else details["items"]) == expected[field]
            if details is not None:
                assert details["total_count"] == details["returned_count"] == len(expected[field])
                assert details["omitted_count"] == 0
        tail_states = _value(row, "tail_extinct_states")
        if tail:
            assert (None if tail_states is None else tail_states["items"]) == expected["tail_extinct_states"]
        else:
            assert tail_states is None
            assert "R_LONGITUDINAL_FAMILY_NOT_REQUESTED" in row["tail_extinct_states"]["reason_codes"]
        for name in ("record_count_delta", "support_delta", "gini_simpson_diversity_delta"):
            delta = row[name]
            assert delta["scope_id"] is None and delta["denominator"] is None
            assert delta["denominator_reason"] == "not_applicable_to_difference"
            assert delta["earlier_scope_id"] and delta["later_scope_id"]
            assert "scope" not in delta and "representation" not in delta
    execution = payload["capabilities"]["dataset_longitudinal"]["longitudinal_execution"]
    assert execution["status"] == result.execution_status.value
    for row in (*execution["snapshot_statuses"], *execution["comparison_statuses"]):
        assert set(row["families"]) == FAMILIES
        assert row["families"]["lineage"]["execution_status"] == "not_requested"


