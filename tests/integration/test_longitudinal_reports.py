def test_redacted_versions_join_context_and_retained_chronology(tmp_path):
    case = _case("lexical_order_context_unloaded")
    versions = {version: "VERSION_PRIVATE_" + version for version in case["order_document"]["version_order"]}
    def rename(value):
        if type(value) is str:
            return versions.get(value, value)
        if type(value) is list:
            return [rename(item) for item in value]
        if type(value) is dict:
            return {versions.get(key, key): rename(item) for key, item in value.items()}
        return value
    case = rename(case)
    report, _, _ = _report(case, tmp_path)
    original = _checked(report)
    view = privacy_view(report, mode="redacted", protection=IdentifierProtection(secret=SECRET))
    protected = _checked(view)
    version_map = dict(zip(original["inputs"]["version_order"], protected["inputs"]["version_order"], strict=True))
    descriptors = protected["inputs"]["longitudinal"]["snapshots"]
    assert [row["dataset_version"] for row in descriptors] == [version_map[version] for version in case["selected_versions"]]
    context = protected["inputs"]["longitudinal"]["context_versions"]
    assert context["items"] == [version_map[version] for version in sorted(case["context_versions"])]
    assert "VERSION_PRIVATE_" not in render_json(view) + render_markdown(view)
    assert [row["snapshot_id"] for row in descriptors] == ["s0001", "s0002"]


